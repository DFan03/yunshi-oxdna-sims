#!/usr/bin/env python3
import os
import shutil
import glob
import stat

def find_md_directory():
    """
    Assume current dir is something like '1_analysis' and we want the sibling '1_md'.
    If that pattern is not found, fall back to a directory named 'md' in the parent.
    """
    cwd = os.getcwd()
    base = os.path.basename(cwd)
    parent = os.path.dirname(cwd)

    if base.endswith("_analysis"):
        md_name = base.replace("_analysis", "_md")
        md_dir = os.path.join(parent, md_name)
        if os.path.isdir(md_dir):
            return md_dir

    # Fallback: "../md"
    fallback = os.path.join(parent, "md")
    if os.path.isdir(fallback):
        return fallback

    raise FileNotFoundError(
        "Could not find MD directory. Expected sibling '*_md' or 'md' next to this analysis directory."
    )

def copy_from_md(md_dir, analysis_dir):
    """
    Copy selected files from md_dir to analysis_dir.
    Patterns:
      *trj.dat, *.top, *energy.dat, *_input.txt, *init_conf.dat
    """
    patterns = [
        "*trj.dat",
        "*.top",
        "*energy.dat",
        "*_input.txt",
        "*init_conf.dat",
    ]

    for pattern in patterns:
        src_pattern = os.path.join(md_dir, pattern)
        for src in glob.glob(src_pattern):
            dst = os.path.join(analysis_dir, os.path.basename(src))
            print(f"Copying {src} -> {dst}")
            shutil.copy2(src, dst)

def copy_analysis_tools(analysis_dir):
    """
    Copy everything from ~/rna_utils/analysis_tools/ into analysis_dir.
    """
    tools_dir = os.path.expanduser("~/rna_utils/analysis_tools")
    if not os.path.isdir(tools_dir):
        print(f"Warning: tools directory '{tools_dir}' not found; skipping tool copy.")
        return

    for name in os.listdir(tools_dir):
        src = os.path.join(tools_dir, name)
        dst = os.path.join(analysis_dir, name)
        if os.path.isfile(src):
            print(f"Copying tool {src} -> {dst}")
            shutil.copy2(src, dst)

def update_input_files(analysis_dir):
    """
    For each *_input.txt in analysis_dir:
      - Replace first two lines:
        topology = <something>
        conf_file = <something>
      with:
        topology = <topology_file_name>.top
        conf_file = <init_conf_file_name>.dat

      - Also replace:
        seq_dep_file = /opt/oxdna/oxDNA/rna_sequence_dependent_parameters.txt
        with:
        seq_dep_file = /home/dfan/inputs_paras_oxDNA/rna_sequence_dependent_parameters.txt
    """
    cwd = analysis_dir
    top_files = glob.glob(os.path.join(cwd, "*.top"))
    init_conf_files = glob.glob(os.path.join(cwd, "*init_conf.dat"))

    if not top_files:
        raise FileNotFoundError("No '*.top' file found in analysis directory.")
    if not init_conf_files:
        raise FileNotFoundError("No '*init_conf.dat' file found in analysis directory.")

    top_basename = os.path.basename(top_files[0])
    init_conf_basename = os.path.basename(init_conf_files[0])

    input_files = glob.glob(os.path.join(cwd, "*_input.txt"))
    if not input_files:
        print("Warning: no '*_input.txt' files found to update.")
        return

    for fpath in input_files:
        print(f"Updating input file: {fpath}")
        with open(fpath, "r") as f:
            lines = f.readlines()

        # Ensure at least two lines
        while len(lines) < 2:
            lines.append("\n")

        # Update first two lines
        lines[0] = f"topology = {top_basename}\n"
        lines[1] = f"conf_file = {init_conf_basename}\n"

        # Update seq_dep_file line(s) wherever they occur
        new_seq_dep = "seq_dep_file = /home/dfan/inputs_paras_oxDNA/rna_sequence_dependent_parameters.txt\n"
        for i, line in enumerate(lines):
            if line.strip().startswith("seq_dep_file"):
                lines[i] = new_seq_dep

        with open(fpath, "w") as f:
            f.writelines(lines)

def write_cmds_script(analysis_dir):
    """
    Write a shell script 'cmds.sh' in analysis_dir with the requested commands
    and 2-second sleeps between them.
    """
    script_path = os.path.join(analysis_dir, "cmds.sh")

    script_contents = """#!/bin/bash

# Commands for trajectory analysis (generated by Python script)

oat mean -p 4 -o mean.dat -d devs.json *trj.dat
sleep 1

oat align -p 4 *trj.dat align.dat
sleep 1

python hb_cal.py *_input.txt *trj.dat kissingloop.csv --output KL_HB.csv
sleep 1

python total_hbond_cal.py *input.txt *trj.dat --output Total_HB.csv
sleep 1

python signed_helical_bent_twist_cal.py align.dat helixces.txt

"""

    with open(script_path, "w") as f:
        f.write(script_contents)

    # Make the script executable
    st = os.stat(script_path)
    os.chmod(script_path, st.st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

    print(f"Written command script: {script_path}")
    print("You can run it with: bash cmds.sh")

def main():
    analysis_dir = os.getcwd()
    print(f"Analysis directory: {analysis_dir}")

    md_dir = find_md_directory()
    print(f"MD directory: {md_dir}")

    copy_from_md(md_dir, analysis_dir)
    copy_analysis_tools(analysis_dir)
    update_input_files(analysis_dir)
    write_cmds_script(analysis_dir)

if __name__ == "__main__":
    main()
