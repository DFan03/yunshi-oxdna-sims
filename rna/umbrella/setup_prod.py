"""
set_prod_run.py
---------------
Finds all window_*/prod/ directories in the current working directory and
generates run_prod.sh with sequential oxDNA production commands.

Each window prints start/end messages and elapsed time in seconds.

Usage:
    python set_prod_run.py
"""

import os
import re
import stat

OXDNA_BIN  = "/home/dfan/oxDNA/build/bin/oxDNA"
INPUT_FILE = "input.txt"
LOG_FILE   = "run.log"
OUT_SCRIPT = "run_prod.sh"


def main():
    cwd = os.getcwd()

    # Find and sort window_* directories
    windows = sorted(
        d for d in os.listdir(cwd)
        if os.path.isdir(os.path.join(cwd, d)) and re.match(r'^window_', d)
    )

    if not windows:
        print("No window_* directories found in current directory.")
        return

    print(f"Found {len(windows)} window directories:")
    for w in windows:
        print(f"  {w}")

    lines = [
        "#!/bin/bash",
        "# Auto-generated by set_prod_run.py",
        "set -e",
        "",
    ]

    for w in windows:
        prod_path  = os.path.join(cwd, w, "prod")
        input_path = os.path.join(prod_path, INPUT_FILE)

        if not os.path.isdir(prod_path):
            print(f"  WARNING: {prod_path} not found, skipping {w}.")
            continue
        if not os.path.isfile(input_path):
            print(f"  WARNING: {input_path} not found, skipping {w}.")
            continue

        lines += [
            f"# --- {w} ---",
            f"echo '[{w}] starting...'",
            f"T_START_{w}=$(date +%s)",
            f"cd {prod_path} && {OXDNA_BIN} {INPUT_FILE} > {LOG_FILE} 2>&1",
            f"T_END_{w}=$(date +%s)",
            f"echo '[{w}] done. Elapsed: $(( T_END_{w} - T_START_{w} )) seconds'",
            "",
        ]

    lines.append('echo "All production runs complete."')

    script_path = os.path.join(cwd, OUT_SCRIPT)
    with open(script_path, "w") as f:
        f.write("\n".join(lines) + "\n")

    os.chmod(script_path, os.stat(script_path).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

    print(f"\nScript written to: {script_path}")
    print(f"Run with: bash {OUT_SCRIPT}")


if __name__ == "__main__":
    main()

