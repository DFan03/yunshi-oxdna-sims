"""
setup_umbrella.py
-----------------
Reads umbrella_params.txt and sets up all umbrella sampling windows.

Force scheme   : mutual_trap between anchor_a and anchor_b.
Distance metric: anchor-anchor distance (also used as the reaction coordinate).

Run sequence   : all equil windows first (chained), then all production.

Required params:
    topology, conf_file
    anchor_a, anchor_b
    xi_start, xi_end, n_windows, stiff
    equil_steps, prod_steps, md_template, oxdna_bin

Optional params:
    temperature         (default: 20C)
    salt_concentration  (default: 1)
    seq_dep_file

Usage:
    python setup_umbrella.py umbrella_params.txt

Notes:
    - xi_start : anchor-anchor distance for the first window
    - xi_end   : anchor-anchor distance for the last window
    - Windows are spaced linearly from xi_start to xi_end.
      The direction (opening vs closing) is determined by which is larger.
    - Equilibrations are chained: each window starts from the last
      configuration of the previous window.
"""

import os
import sys
import shutil
import numpy as np


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def parse_params(filepath):
    params = {}
    with open(filepath, encoding='utf-8-sig') as f:
        for lineno, line in enumerate(f, 1):
            line = line.rstrip('\r\n').strip()
            if not line or line.startswith('#'):
                continue
            if '=' not in line:
                print(f"  [params] Line {lineno} skipped (no '='): {line!r}")
                continue
            key, _, val = line.partition('=')
            key = key.strip()
            val = val.strip()
            if ' #' in val:
                val = val[:val.index(' #')].strip()
            if key in params:
                print(f"  [params] Warning: duplicate key '{key}' on line {lineno}, overwriting.")
            params[key] = val
    return params


def require(params, *keys):
    missing = [k for k in keys if k not in params]
    if missing:
        print("\nERROR: Missing required keys in params file:")
        for k in missing:
            print(f"  - {k}")
        sys.exit(1)


def read_template(filepath):
    with open(filepath) as f:
        return f.read()


def write_input(template, replacements, out_path):
    lines = template.splitlines()
    used_keys = set()
    new_lines = []
    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith('#'):
            new_lines.append(line)
            continue
        if '=' in line:
            key = line.split('=')[0].strip()
            if key in replacements:
                if key not in used_keys:
                    new_lines.append(f"{key} = {replacements[key]}")
                    used_keys.add(key)
                continue
        new_lines.append(line)
    for key, val in replacements.items():
        if key not in used_keys:
            new_lines.append(f"{key} = {val}")
    with open(out_path, 'w') as f:
        f.write('\n'.join(new_lines) + '\n')


def write_forces(anchor_a, anchor_b, stiff, r0, out_path):
    content = (
        "# Pull anchor A toward anchor B\n"
        "{\n"
        "type = mutual_trap\n"
        f"particle = {anchor_a}\n"
        f"ref_particle = {anchor_b}\n"
        f"stiff = {stiff}\n"
        f"r0 = {r0:.6f}\n"
        "PBC = 0\n"
        "}\n"
        "\n"
        "# Pull anchor B toward anchor A\n"
        "{\n"
        "type = mutual_trap\n"
        f"particle = {anchor_b}\n"
        f"ref_particle = {anchor_a}\n"
        f"stiff = {stiff}\n"
        f"r0 = {r0:.6f}\n"
        "PBC = 0\n"
        "}\n"
    )
    with open(out_path, 'w') as f:
        f.write(content)


def write_check_script(path, anchor_a, anchor_b, xi0):
    """
    Prints the anchor-anchor distance (the biased coordinate) and compares
    it to the window target xi0.
    """
    lines = [
        '#!/usr/bin/env python3',
        '# Auto-generated by setup_umbrella.py',
        'import sys, math',
        '',
        f'ANCHOR_A = {anchor_a}',
        f'ANCHOR_B = {anchor_b}',
        f'XI0      = {xi0:.6f}',
        '',
        'def parse_dat_coords(filepath):',
        '    coords = []',
        '    with open(filepath) as f:',
        '        for line in f:',
        '            line = line.strip()',
        '            if not line or line[0] in ("t", "b", "E"):',
        '                continue',
        '            vals = line.split()',
        '            if len(vals) < 3:',
        '                continue',
        '            try:',
        '                coords.append([float(vals[0]), float(vals[1]), float(vals[2])])',
        '            except ValueError:',
        '                continue',
        '    return coords',
        '',
        'def dist(a, b):',
        '    return math.sqrt(sum((a[k]-b[k])**2 for k in range(3)))',
        '',
        'coords = parse_dat_coords("last_conf.dat")',
        'if not coords:',
        '    print("ERROR: could not parse last_conf.dat")',
        '    sys.exit(1)',
        '',
        'pa     = coords[ANCHOR_A]',
        'pb     = coords[ANCHOR_B]',
        'd_anch = dist(pa, pb)',
        '',
        'print("  target xi0      : " + str(round(XI0, 4)))',
        'print("  anchor distance : " + str(round(d_anch, 4)))',
        'print("  difference      : " + str(round(d_anch - XI0, 4)))',
    ]
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    os.chmod(path, 0o755)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

MIN_PRINT_INTERVAL = 50000


def main():
    if len(sys.argv) != 2:
        print("Usage: python setup_umbrella.py umbrella_params.txt")
        sys.exit(1)

    param_file = sys.argv[1]
    if not os.path.isfile(param_file):
        print(f"ERROR: params file not found: {param_file}")
        sys.exit(1)

    base_dir = os.path.dirname(os.path.abspath(param_file))
    p = parse_params(param_file)

    print(f"\nParsed {len(p)} keys from {param_file}:")
    for k, v in sorted(p.items()):
        print(f"  {k} = {v}")
    print()

    require(p,
        'topology', 'conf_file',
        'anchor_a', 'anchor_b',
        'xi_start', 'xi_end', 'n_windows', 'stiff',
        'equil_steps', 'prod_steps', 'md_template', 'oxdna_bin'
    )

    topology   = os.path.join(base_dir, p['topology'])
    conf_file  = os.path.join(base_dir, p['conf_file'])
    template_f = os.path.join(base_dir, p['md_template'])
    oxdna_bin  = p['oxdna_bin']

    anchor_a    = int(p['anchor_a'])
    anchor_b    = int(p['anchor_b'])

    xi_start    = float(p['xi_start'])
    xi_end      = float(p['xi_end'])
    n_windows   = int(p['n_windows'])
    stiff       = float(p['stiff'])
    equil_steps = int(p['equil_steps'])
    prod_steps  = int(p['prod_steps'])

    temperature        = p.get('temperature', '20C')
    salt_concentration = p.get('salt_concentration', '1')
    seq_dep_file       = p.get('seq_dep_file', '')

    for label, path in [('topology', topology), ('conf_file', conf_file),
                        ('md_template', template_f)]:
        if not os.path.isfile(path):
            print(f"ERROR: '{label}' file not found: {path}")
            sys.exit(1)

    print(f"Anchor A    : particle {anchor_a}")
    print(f"Anchor B    : particle {anchor_b}")

    xi_values = np.linspace(xi_start, xi_end, n_windows)
    spacing   = abs(xi_values[1] - xi_values[0]) if n_windows > 1 else 0.0
    direction = "increasing" if xi_end > xi_start else "decreasing"
    print(f"Windows     : {n_windows}  |  xi: {xi_start} -> {xi_end}  ({direction})  |  spacing: {spacing:.4f}")

    prod_print_conf   = max(MIN_PRINT_INTERVAL, prod_steps // 2000)
    prod_print_energy = max(MIN_PRINT_INTERVAL, prod_steps // 2000)
    prod_n_frames     = prod_steps // prod_print_conf
    print(f"Production  : {prod_steps} steps  |  print every {prod_print_conf}  |  ~{prod_n_frames} frames/window")

    template     = read_template(template_f)
    top_basename = os.path.basename(topology)

    out_root = os.path.join(base_dir, 'umbrella')
    os.makedirs(out_root, exist_ok=True)

    equil_cmds = ["# ── Phase 1: all equilibrations (chained) ──────────────────────────"]
    prod_cmds  = ["# ── Phase 2: all productions ────────────────────────────────────────"]

    for i, xi0 in enumerate(xi_values):
        win_name  = f"window_{i:02d}"
        win_dir   = os.path.join(out_root, win_name)
        equil_dir = os.path.join(win_dir, 'equil')
        prod_dir  = os.path.join(win_dir, 'prod')
        os.makedirs(equil_dir, exist_ok=True)
        os.makedirs(prod_dir,  exist_ok=True)

        shutil.copy(topology, os.path.join(equil_dir, top_basename))
        shutil.copy(topology, os.path.join(prod_dir,  top_basename))

        write_forces(anchor_a, anchor_b, stiff, xi0, os.path.join(equil_dir, 'forces.txt'))
        write_forces(anchor_a, anchor_b, stiff, xi0, os.path.join(prod_dir,  'forces.txt'))
        write_check_script(os.path.join(equil_dir, 'check_equil.py'),
                           anchor_a, anchor_b, xi0)

        rel_topology = top_basename

        # Chained init: window 0 uses the global conf_file; others use previous equil output
        if i == 0:
            equil_conf = os.path.relpath(conf_file, equil_dir)
        else:
            prev_equil_dir = os.path.join(out_root, f"window_{i-1:02d}", 'equil')
            equil_conf = os.path.relpath(
                os.path.join(prev_equil_dir, 'last_conf.dat'), equil_dir)

        # Equilibration input
        equil_replacements = {
            'topology':             rel_topology,
            'conf_file':            equil_conf,
            'T':                    temperature,
            'salt_concentration':   salt_concentration,
            'seq_dep_file':         seq_dep_file,
            'steps':                str(equil_steps),
            'print_conf_interval':  str(equil_steps),
            'print_energy_every':   str(equil_steps),
            'external_forces':      '1',
            'external_forces_file': 'forces.txt',
            'lastconf_file':        'last_conf.dat',
            'trajectory_file':      'trajectory.dat',
            'energy_file':          'energy.dat',
            'refresh_vel':          '1',
            'restart_step_counter': '1',
        }
        write_input(template, equil_replacements, os.path.join(equil_dir, 'input.txt'))

        # Production input
        prod_conf = os.path.relpath(
            os.path.join(equil_dir, 'last_conf.dat'), prod_dir)

        prod_replacements = {
            'topology':             rel_topology,
            'conf_file':            prod_conf,
            'T':                    temperature,
            'salt_concentration':   salt_concentration,
            'seq_dep_file':         seq_dep_file,
            'steps':                str(prod_steps),
            'print_conf_interval':  str(prod_print_conf),
            'print_energy_every':   str(prod_print_energy),
            'external_forces':      '1',
            'external_forces_file': 'forces.txt',
            'lastconf_file':        'last_conf.dat',
            'trajectory_file':      'trajectory.dat',
            'energy_file':          'energy.dat',
            'refresh_vel':          '0',
            'restart_step_counter': '1',
        }
        write_input(template, prod_replacements, os.path.join(prod_dir, 'input.txt'))

        # Shell commands
        equil_cmds.append(f"cd {equil_dir} && {oxdna_bin} input.txt > run.log 2>&1")
        chain_note = "(from conf_file)" if i == 0 else f"(from window_{i-1:02d}/equil)"
        print(f"  [{win_name}]  xi0 = {xi0:.4f}  {chain_note}")

    run_script = os.path.join(out_root, 'run_all.sh')
        
if __name__ == '__main__':
    main()

